/* Generates lib/geoDots.ts — the Texas outline the landing's dot matrix fills,
 * and the full-detail rings (islands included) the map masks everything else with.
 *
 * Input is Natural Earth GeoJSON (public domain), downloaded by hand so the
 * build never touches the network:
 *   ne_50m_admin_1_states_provinces.geojson
 *
 *   node scripts/build-geo-dots.mjs <states.geojson>
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const [statesPath] = process.argv.slice(2);
if (!statesPath) {
  console.error('usage: node scripts/build-geo-dots.mjs <states.geojson>');
  process.exit(1);
}

// Texas ring is simplified to roughly this many vertices.
const OUTLINE_STEP_DEG = 0.12;

const states = JSON.parse(readFileSync(statesPath, 'utf8'));

/** Every outer ring (holes are ignored). */
function rings(geometry) {
  if (geometry.type === 'Polygon') return [geometry.coordinates[0]];
  if (geometry.type === 'MultiPolygon') return geometry.coordinates.map((p) => p[0]);
  return [];
}

const texas = states.features.find((f) => f.properties?.name === 'Texas');
if (!texas) throw new Error('Texas not found in states file');
const mainland = rings(texas.geometry).sort((a, b) => b.length - a.length)[0];

// Drop vertices closer than OUTLINE_STEP_DEG to the last kept one.
const outline = [];
for (const [lng, lat] of mainland) {
  const last = outline[outline.length - 1];
  if (!last || Math.hypot(lng - last[1], lat - last[0]) >= OUTLINE_STEP_DEG) {
    outline.push([+lat.toFixed(3), +lng.toFixed(3)]);
  }
}

// Every ring at source resolution, for the map mask: at street zoom a
// simplified coast would cover Galveston and the barrier islands.
const allRings = rings(texas.geometry).map((ring) =>
  ring.map(([lng, lat]) => [+lat.toFixed(4), +lng.toFixed(4)]),
);

const out = `/* AUTO-GENERATED by scripts/build-geo-dots.mjs from Natural Earth (public
 * domain). Do not hand-edit — rerun the script. */

/** Texas mainland outline as [lat, lng] pairs, simplified. */
export const TEXAS_OUTLINE: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(outline)};

/** Every Texas ring (mainland and islands) as [lat, lng] pairs, unsimplified. */
export const TEXAS_RINGS: ReadonlyArray<ReadonlyArray<readonly [number, number]>> = ${JSON.stringify(allRings)};
`;

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '..', 'lib', 'geoDots.ts'), out);
console.log(`texas outline: ${outline.length} vertices, rings: ${allRings.length} (${allRings.flat().length} vertices)`);
