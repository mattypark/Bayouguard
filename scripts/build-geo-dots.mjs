/* Generates lib/geoDots.ts — the land dots for the landing globe and the Texas
 * outline the dot-matrix variant fills.
 *
 * Inputs are Natural Earth GeoJSON (public domain), downloaded by hand so the
 * build never touches the network:
 *   ne_110m_land.geojson
 *   ne_50m_admin_1_states_provinces.geojson
 *
 *   node scripts/build-geo-dots.mjs <land.geojson> <states.geojson>
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const [landPath, statesPath] = process.argv.slice(2);
if (!landPath || !statesPath) {
  console.error('usage: node scripts/build-geo-dots.mjs <land.geojson> <states.geojson>');
  process.exit(1);
}

// Sphere samples before the land mask. ~30% of Earth is land, so this lands
// near 2,700 dots — dense enough to read as continents, cheap enough to spin.
const SPHERE_SAMPLES = 9000;
// Texas ring is simplified to roughly this many vertices.
const OUTLINE_STEP_DEG = 0.12;

const land = JSON.parse(readFileSync(landPath, 'utf8'));
const states = JSON.parse(readFileSync(statesPath, 'utf8'));

/** Every outer ring (holes are rare at 110m and ignored). */
function rings(geometry) {
  if (geometry.type === 'Polygon') return [geometry.coordinates[0]];
  if (geometry.type === 'MultiPolygon') return geometry.coordinates.map((p) => p[0]);
  return [];
}

function inRing(lng, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
      inside = !inside;
    }
  }
  return inside;
}

const landRings = land.features.flatMap((f) => rings(f.geometry));
// Bounding boxes first — the point-in-polygon test is the slow part.
const boxed = landRings.map((ring) => {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const [x, y] of ring) {
    minX = Math.min(minX, x); maxX = Math.max(maxX, x);
    minY = Math.min(minY, y); maxY = Math.max(maxY, y);
  }
  return { ring, minX, minY, maxX, maxY };
});

const onLand = (lng, lat) =>
  boxed.some(
    (b) =>
      lng >= b.minX && lng <= b.maxX && lat >= b.minY && lat <= b.maxY &&
      inRing(lng, lat, b.ring),
  );

// Fibonacci sphere: an even shell, so the land reads as texture, not rows.
const GOLDEN = Math.PI * (3 - Math.sqrt(5));
const landDots = [];
for (let i = 0; i < SPHERE_SAMPLES; i++) {
  const y = 1 - (2 * (i + 0.5)) / SPHERE_SAMPLES;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lng = ((((i * GOLDEN * 180) / Math.PI) % 360) + 540) % 360 - 180;
  if (lat < -60) continue; // Antarctica is a white smear at the bottom; drop it.
  if (onLand(lng, lat)) landDots.push(+lat.toFixed(2), +lng.toFixed(2));
}

const texas = states.features.find((f) => f.properties?.name === 'Texas');
if (!texas) throw new Error('Texas not found in states file');
const mainland = rings(texas.geometry).sort((a, b) => b.length - a.length)[0];

// Drop vertices closer than OUTLINE_STEP_DEG to the last kept one.
const outline = [];
for (const [lng, lat] of mainland) {
  const last = outline[outline.length - 1];
  if (!last || Math.hypot(lng - last[1], lat - last[0]) >= OUTLINE_STEP_DEG) {
    outline.push([+lat.toFixed(3), +lng.toFixed(3)]);
  }
}

const out = `/* AUTO-GENERATED by scripts/build-geo-dots.mjs from Natural Earth (public
 * domain). Do not hand-edit — rerun the script. */

/** Land dots on an even sphere, flattened [lat, lng, lat, lng, …]. */
export const LAND_DOTS: readonly number[] = ${JSON.stringify(landDots)};

/** Texas mainland outline as [lat, lng] pairs, simplified. */
export const TEXAS_OUTLINE: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(outline)};
`;

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, '..', 'lib', 'geoDots.ts'), out);
console.log(`land dots: ${landDots.length / 2}, texas outline: ${outline.length} vertices`);
