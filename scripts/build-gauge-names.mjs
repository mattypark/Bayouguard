/* Regenerates lib/gaugeNames.ts from the Harris County Flood Warning System
 * feed. Each feature's geometry.Text reads "<SiteId> <Channel> @ <Crossing>";
 * the id prefix is dropped. Run: node scripts/build-gauge-names.mjs */

import { writeFileSync } from 'node:fs';

const REGIONS = [1, 3, 4, 10, 14, 18, 19, 20, 21, 22, 23, 24, 25, 26];
const url =
  'https://www.harriscountyfws.org/Home/GetSiteRecentData?' +
  REGIONS.map((r) => `regionId=${r}`).join('&') +
  '&timeSpan=7&dt=1779069600000';

const res = await fetch(url, { headers: { Referer: 'https://www.harriscountyfws.org/' } });
if (!res.ok) throw new Error(`HCFWS feed ${res.status}`);
const { features } = await res.json();

const names = new Map();
for (const f of features) {
  const id = f?.properties?.SiteId;
  const text = f?.geometry?.Text;
  if (typeof id !== 'number' || typeof text !== 'string') continue;
  const name = text.replace(/^\s*\d+\s+/, '').trim();
  if (name) names.set(id, name);
}

const rows = [...names.entries()]
  .sort((a, b) => a[0] - b[0])
  .map(([id, name]) => `  ${id}: ${JSON.stringify(name)},`)
  .join('\n');

writeFileSync(
  new URL('../lib/gaugeNames.ts', import.meta.url),
  `/* HCFWS site id -> human gauge name ("Brays Bayou @ Main Street").
 * Generated by scripts/build-gauge-names.mjs from the HCFWS feed on ${new Date().toISOString().slice(0, 10)};
 * the live feed's names win when it is reachable. Server-only (keeps ~${names.size} names out of the bundle). */

export const GAUGE_NAMES: Record<number, string> = {
${rows}
};

/** Live feed name, then the generated table, then the bare id. */
export function gaugeName(id: number, live?: string): string {
  return live || GAUGE_NAMES[id] || \`Gauge \${id}\`;
}
`,
);
console.log(`wrote ${names.size} gauge names`);
